-- The identity-platform tables of SQLite schemas 15 and 16 (route-scoped
-- service credentials; the Kubernetes workload principal registry), so a
-- current SQLite store migrates and both backends hold the same data.

CREATE TABLE service_credentials (
    credential_id      TEXT PRIMARY KEY CHECK (length(credential_id) BETWEEN 3 AND 48),
    routes             TEXT NOT NULL CHECK (length(routes) <= 4096),
    audiences          TEXT NOT NULL CHECK (length(audiences) <= 2048),
    client_spki_sha256 TEXT CHECK (client_spki_sha256 IS NULL OR length(client_spki_sha256) = 64),
    client_san         TEXT CHECK (client_san IS NULL OR length(client_san) BETWEEN 1 AND 512),
    current_sha256     TEXT NOT NULL CHECK (length(current_sha256) = 64),
    current_since      BIGINT NOT NULL,
    next_sha256        TEXT CHECK (next_sha256 IS NULL OR length(next_sha256) = 64),
    next_since         BIGINT,
    expires_at         BIGINT NOT NULL,
    rate_per_minute    BIGINT NOT NULL CHECK (rate_per_minute BETWEEN 1 AND 6000),
    burst              BIGINT NOT NULL CHECK (burst BETWEEN 1 AND 1000),
    note               TEXT CHECK (note IS NULL OR length(note) <= 256),
    created_at         BIGINT NOT NULL,
    revoked_at         BIGINT,
    revision           BIGINT NOT NULL DEFAULT 1 CHECK (revision >= 1),
    CHECK (client_spki_sha256 IS NOT NULL OR client_san IS NOT NULL),
    CHECK ((next_sha256 IS NULL) = (next_since IS NULL))
);

-- `position` is SQLite's AUTOINCREMENT key (a snapshot cursor): handed out
-- by an identity here, copied as is by the migration tool.
CREATE TABLE workload_principals (
    position            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    principal           TEXT NOT NULL UNIQUE CHECK (length(principal) = 68 AND substr(principal, 1, 4) = 'wk2:'),
    subject_ref         TEXT NOT NULL CHECK (length(subject_ref) = 50 AND substr(subject_ref, 1, 2) = 's_'),
    spiffe_id           TEXT CHECK (spiffe_id IS NULL OR length(spiffe_id) <= 2048),
    service             TEXT NOT NULL CHECK (length(service) BETWEEN 1 AND 128),
    cluster             TEXT NOT NULL CHECK (length(cluster) BETWEEN 1 AND 128),
    namespace           TEXT NOT NULL CHECK (length(namespace) BETWEEN 1 AND 63),
    service_account     TEXT NOT NULL CHECK (length(service_account) BETWEEN 1 AND 253),
    service_account_uid TEXT NOT NULL CHECK (length(service_account_uid) BETWEEN 1 AND 128),
    status              TEXT NOT NULL CHECK (status IN ('active', 'retired')),
    first_seen_at       BIGINT NOT NULL,
    last_seen_at        BIGINT NOT NULL,
    retired_at          BIGINT,
    cause               TEXT CHECK (cause IS NULL OR cause IN ('deleted', 'uid_changed')),
    replacement         TEXT CHECK (replacement IS NULL OR length(replacement) = 68),
    CHECK ((status = 'retired') = (retired_at IS NOT NULL))
);
CREATE FUNCTION hopae_workload_retired_is_final() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status = 'retired' AND NEW.status <> 'retired' THEN
        RAISE EXCEPTION 'retired workload principal is final' USING ERRCODE = 'P0001';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER workload_principal_retired_is_final BEFORE UPDATE OF status ON workload_principals
    FOR EACH ROW EXECUTE FUNCTION hopae_workload_retired_is_final();
CREATE TABLE workload_legacy_mappings (
    legacy_subject_ref TEXT NOT NULL CHECK (length(legacy_subject_ref) = 50),
    principal          TEXT NOT NULL REFERENCES workload_principals (principal),
    observed_at        BIGINT NOT NULL,
    PRIMARY KEY (legacy_subject_ref, principal)
);
CREATE INDEX workload_legacy_mappings_principal ON workload_legacy_mappings (principal);
